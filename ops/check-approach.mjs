import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {connect} from './cdp.mjs';
const url=process.argv[2]||'http://127.0.0.1:18083/';
const b=await connect(url,1024,640),samples={};
const prefix='qa/physics-full';
const snap=()=>b.evaluate('window.__flightSim.snapshot()');
const tap=async(code,key)=>{await b.key(code,key);await b.key(code,key,'keyUp');};
try{
 await b.waitFor('window.__flightSim && !document.querySelector(".primary-button").disabled',30000);
 assert.equal((await snap()).scenario,'full');assert.equal((await snap()).autoPilot,false);
 await b.screenshot(`${prefix}-briefing.png`);
 await b.click('.flight-card .primary-button');
 await tap('KeyI','i');await tap('KeyA','a');
 await b.waitFor('window.__flightSim.snapshot().locCaptured && window.__flightSim.snapshot().gsCaptured',30000);
 await b.click('[aria-label="目标速度增加"]');
 assert.equal((await snap()).speedMode,'selected');
 await b.click('.fcu-label');assert.equal((await snap()).speedMode,'managed');
 await tap('KeyF','f');assert.equal((await snap()).flaps,2);
 await tap('KeyG','g');await tap('KeyB','b');await tap('KeyM','m');await tap('KeyM','m');
 await b.waitFor('window.__flightSim.snapshot().speed*1.94384<185',30000);
 await tap('KeyF','f');assert.equal((await snap()).flaps,3);
 await b.waitFor('window.__flightSim.snapshot().speed*1.94384<177',30000);
 await tap('KeyF','f');assert.equal((await snap()).flaps,4);
 await b.waitFor('window.__flightSim.snapshot().gearPosition>.98 && window.__flightSim.snapshot().flapPosition>3.95',30000);
 await tap('KeyC','c');assert.equal((await snap()).landingChecklistConfirmed,true);
 await b.screenshot(`${prefix}-ils.png`);
 samples.configured=await snap();
 await tap('KeyX','x');assert.equal((await snap()).timeScale,2);
 console.log('APPR/ILS, FCU speed, timed flaps/gear, checklist and 2x verified.');
 await b.waitFor('window.__flightSim.snapshot().gates.some(g=>g.height===1000)',240000);
 await b.waitFor('window.__flightSim.snapshot().timeScale===1');
 samples.gate1000=await snap();assert(samples.gate1000.gates.find(g=>g.height===1000).passed);
 assert.equal(samples.gate1000.timeScale,1);
 await b.screenshot(`${prefix}-1000.png`);
 console.log('Full approach: 1000 ft gate stable; normal time restored.');
 await b.waitFor('window.__flightSim.snapshot().gates.some(g=>g.height===500)',120000);
 samples.gate500=await snap();assert(samples.gate500.gates.find(g=>g.height===500).passed);
 await b.waitFor('!window.__flightSim.snapshot().autoPilot && (window.__flightSim.snapshot().y-2.8)*3.28084<200',60000);
 console.log('500 ft gate stable; AP disconnected below 200 ft.');
 await b.waitFor('(window.__flightSim.snapshot().y-2.8)*3.28084<32',50000);
 await b.key('ShiftLeft','Shift');await b.key('ArrowDown','ArrowDown');
 await b.waitFor('window.__flightSim.snapshot().pitch>.09 || window.__flightSim.snapshot().landed',15000);
 await b.key('ArrowDown','ArrowDown','keyUp');await b.key('ShiftLeft','Shift','keyUp');
 await tap('KeyZ','z');
 await b.waitFor('window.__flightSim.snapshot().landed || window.__flightSim.snapshot().result',30000);
 let s=await snap();assert.equal(s.landed,true,JSON.stringify(s.result));
 await tap('KeyV','v');
 await b.waitFor('window.__flightSim.snapshot().speed*1.94384<70',30000);await tap('KeyV','v');
 await b.waitFor('window.__flightSim.snapshot().result',30000);
 samples.landing=await snap();assert.equal(samples.landing.result.title,'平安落地');assert(samples.landing.result.success);
 await b.screenshot(`${prefix}-result.png`);
 console.log('Complete full approach and manual landing passed:',samples.landing.result.score);

 const errors=b.events.filter(e=>e.method==='Runtime.exceptionThrown'||(e.method==='Log.entryAdded'&&e.params.entry.level==='error'));
 assert.deepEqual(errors,[]);
 await writeFile(`${prefix}-check.json`,JSON.stringify({url,viewport:{width:1024,height:640},samples,errors},null,2));
 console.log('A320 landing browser checks passed; run check-goaround.mjs separately.');
}finally{await writeFile(`${prefix}-progress.json`,JSON.stringify({url,samples},null,2));await b.close();}
